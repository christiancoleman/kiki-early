const ple_switch_t *ple_lookup_switch_by_channel_bit(uint8_t channel, uint8_t bit_idx) {
    for (size_t i = 0; i < ple_switches_count; i++) {
        if (ple_switches[i].channel == channel && ple_switches[i].bit_idx == bit_idx)
            return &ple_switches[i];
    }
    return NULL;
}

